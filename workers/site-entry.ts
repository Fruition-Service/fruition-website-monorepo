// Entry point of the fruition-landing Worker (wrangler.jsonc `main`). It wraps
// the worker OpenNext generates in .open-next/worker.js and adds one thing:
// caching for /_next/image.
//
// OpenNext's image handler only sends Cache-Control for images it can prove are
// immutable, which in practice is none of ours: every Sanity logo, avatar and
// hero went out with no Cache-Control at all (Lighthouse "uses-long-cache-ttl",
// 31 resources, 30 Oct 2026). Browsers re-downloaded them on every visit, and
// every request paid a fresh Sanity fetch plus an Images binding transform.
//
// Now each transformed image is kept in the colo's cache and served with a
// browser TTL. Sanity asset URLs are content-hashed (a new upload is a new
// URL), so those are safe to keep for a year; files from /public can be
// replaced under the same name, so they get a week. The output format depends
// on the Accept header (AVIF, WebP or the original), so the cache key carries
// the negotiated format and the response keeps `Vary: Accept`.

// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler
import openNext from "../.open-next/worker.js"
// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from "../.open-next/worker.js"

const YEAR = 31536000
const WEEK = 604800

type Ctx = { waitUntil(p: Promise<unknown>): void }
type Handler = { fetch(req: Request, env: unknown, ctx: Ctx): Promise<Response> }
type Env = {
  HUBSPOT_SYNC_SECRET?: string
  WORKER_SELF_REFERENCE?: { fetch(input: string, init?: RequestInit): Promise<Response> }
}

function negotiatedFormat(accept: string): string {
  if (accept.includes("image/avif")) return "avif"
  if (accept.includes("image/webp")) return "webp"
  return "orig"
}

function browserTtl(url: URL): number {
  const src = url.searchParams.get("url") ?? ""
  return src.startsWith("https://cdn.sanity.io/") ? YEAR : WEEK
}

async function cachedImage(request: Request, env: unknown, ctx: Ctx): Promise<Response> {
  const url = new URL(request.url)
  const key = new URL(url)
  key.searchParams.set("__fmt", negotiatedFormat(request.headers.get("Accept") ?? ""))
  const cacheKey = new Request(key.toString(), { method: "GET" })
  const cache = (caches as unknown as { default: Cache }).default

  const hit = await cache.match(cacheKey)
  if (hit) return hit

  const res = await (openNext as Handler).fetch(request, env, ctx)
  if (!res.ok) return res

  const ttl = browserTtl(url)
  const out = new Response(res.body, res)
  if (!out.headers.get("Cache-Control")?.includes("immutable")) {
    out.headers.set("Cache-Control", `public, max-age=${ttl}${ttl === YEAR ? ", immutable" : ""}`)
  }
  out.headers.set("Vary", "Accept")
  ctx.waitUntil(cache.put(cacheKey, out.clone()))
  return out
}

// Cron (wrangler.jsonc `triggers.crons`): the HubSpot -> Fruition blog sync.
// Sent through the WORKER_SELF_REFERENCE service binding so the route runs as
// an ordinary fetch event with OpenNext's full request context; calling the
// OpenNext handler straight from a scheduled event did not run the sync. Uses
// the canonical host or src/middleware.ts would 301 it.
async function runHubSpotBlogSync(env: Env): Promise<void> {
  if (!env.HUBSPOT_SYNC_SECRET || !env.WORKER_SELF_REFERENCE) {
    console.error("[cron] hubspot-blog-sync skipped: secret or self binding missing")
    return
  }
  const res = await env.WORKER_SELF_REFERENCE.fetch("https://www.fruitionservices.io/api/cron/hubspot-blog-sync", {
    method: "POST",
    headers: { "x-sync-secret": env.HUBSPOT_SYNC_SECRET, "x-sync-trigger": "cron" },
  })
  const text = (await res.text()).slice(0, 800)
  if (!res.ok) console.error(`[cron] hubspot-blog-sync ${res.status}: ${text}`)
  else console.log(`[cron] hubspot-blog-sync ok: ${text}`)
}

export default {
  async scheduled(_event: unknown, env: Env, ctx: Ctx): Promise<void> {
    ctx.waitUntil(runHubSpotBlogSync(env))
  },

  async fetch(request: Request, env: unknown, ctx: Ctx): Promise<Response> {
    if (request.method === "GET" && new URL(request.url).pathname === "/_next/image") {
      return cachedImage(request, env, ctx)
    }
    return (openNext as Handler).fetch(request, env, ctx)
  },
}
