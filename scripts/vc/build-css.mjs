#!/usr/bin/env node
/**
 * Ports the approved Version C mock-up stylesheets into the site.
 *
 *   node scripts/vc/build-css.mjs <mockups/review dir>
 *
 * - sys.css (the shared design system) becomes src/styles/vc/base.css, every
 *   selector scoped under `.vc` so the new pages cannot restyle the old ones
 *   (sys.css carries global `section{}`, `.btn`, `.card` rules).
 * - Each page's own <style> block becomes src/styles/vc/pages/<slug>.css,
 *   scoped under `.vc-p-<slug>`, so every page renders exactly like its
 *   approved mock-up even where two mock-ups tuned the same class differently.
 *
 * Scoping adds exactly one class to every selector in both files, so the
 * cascade between sys.css and a page block is the same as in the mock-ups.
 * Everything is wrapped in `@layer components` (DESIGN.md: no unlayered CSS).
 * Keyframes get a `vc-` prefix so they cannot collide with the site's own.
 *
 * Generated files: do not hand-edit, re-run this script.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync } from 'node:fs'
import { tokeniseColors } from './tokenise-colors.mjs'
import { join, dirname } from 'node:path'
import postcss from 'postcss'

/**
 * Code-rendered pages that extend another page's stylesheet: the output is the
 * `from` page's generated file with scripts/vc/extras-<slug>.css appended, so
 * the route renders `vc vc-p-<from> vc-p-<slug>`. `--derived-only` rebuilds just
 * these from the committed `from` files, leaving every other stylesheet alone
 * (a full run drops the lines kept by hand in home.css).
 */
const DERIVED_PAGES = [
  // /post/<slug>: blog post template (review-v3 blog-sap / blog-claude-github mock-ups, 14 Nov 2026).
  { slug: 'blog-post', from: 'consulting-blog' },
  // /thank-you: the contact-us hero with the three-step hand-off (review-v3 thank-you mock-up, 14 Nov 2026).
  { slug: 'thank-you', from: 'contact-us' },
  // /ask-fruit/workspace start screen (review-v3 ask-fruit-workspace mock-up, 14 Nov 2026).
  { slug: 'ask-fruit-workspace', from: 'ask-fruit' },
]

const root = new URL('../../', import.meta.url).pathname
const outDir = join(root, 'src/styles/vc')

function writeDerived() {
  for (const { slug, from } of DERIVED_PAGES) {
    const base = readFileSync(join(outDir, 'pages', `${from}.css`), 'utf8').replace(/\}\s*$/, '')
    const extra = readFileSync(new URL(`./extras-${slug}.css`, import.meta.url), 'utf8')
    writeFileSync(join(outDir, 'pages', `${slug}.css`), tokeniseColors(`${base}\n${extra}\n}\n`))
    console.log(`derived ${slug} from ${from}`)
  }
}

if (process.argv.includes('--derived-only')) {
  writeDerived()
  process.exit(0)
}

const src = process.argv[2]
if (!src) {
  console.error('usage: node scripts/vc/build-css.mjs <mockups/review dir> | --derived-only')
  process.exit(1)
}
mkdirSync(join(outDir, 'pages'), { recursive: true })
mkdirSync(join(root, 'public/vc'), { recursive: true })

const HEADER = '/* GENERATED by scripts/vc/build-css.mjs from the approved Version C mock-ups. Do not edit. */\n'

/** Map one selector to its scoped form. */
function scopeSelector(sel, scope) {
  const s = sel.trim()
  if (s === ':root' || s === 'html' || s === 'body' || s === 'html,body') return scope
  if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)\b\s*/, `${scope} `)
  if (s.startsWith(':root')) return s.replace(':root', scope)
  if (s === '*') return `${scope} *`
  return `${scope} ${s}`
}

function rewriteUrls(value) {
  return value.replace(/url\((['"]?)(?:\.\.\/)?c\/([^)'"]+)\1\)/g, (_m, q, file) => {
    const from = join(src, 'c', file)
    if (existsSync(from)) {
      const to = join(root, 'public/vc', file)
      mkdirSync(dirname(to), { recursive: true })
      copyFileSync(from, to)
    }
    return `url(${q}/vc/${file}${q})`
  })
}

/**
 * Every colour the mock-ups use resolves to a Version C token in globals.css
 * (`--vc-*`), so the palette lives in one place and component CSS carries no
 * raw palette hex (DESIGN.md, the Semantic Token Rule). White and black stay
 * literal: they are not brand colours.
 */
const HEX_TOKENS = {
  '#0f0d14': '--vc-ink', '#fff': null, '#ffffff': null, '#000': null, '#000000': null,
  '#f3f2f6': '--vc-paper-2', '#17141f': '--vc-dark', '#221e2c': '--vc-dark-2',
  '#8015e8': '--vc-accent', '#6a11c2': '--vc-accent-press', '#c79cf6': '--vc-accent-on-dark',
  '#e9d7fd': '--vc-accent-tint', '#10003a': '--vc-midnight', '#1f9d55': '--vc-good',
  '#ece9f2': '--vc-press-light', '#e7e4ee': '--vc-day-hover', '#c9a3fa': '--vc-lilac',
  '#f5eefe': '--vc-tint-1', '#f6f1fe': '--vc-tint-2', '#f3ebfd': '--vc-tint-3', '#f0e4fd': '--vc-tint-4',
  '#ece6f7': '--vc-tint-5', '#f6f0ff': '--vc-tint-6', '#22074d': '--vc-midnight-2',
  '#4a3670': '--vc-plum', '#4674fb': null,
}
const unknownHex = new Set()
function tokeniseHex(value) {
  return value.replace(/#[0-9a-fA-F]{3,6}\b/g, (hex) => {
    const k = hex.toLowerCase()
    if (!(k in HEX_TOKENS)) { unknownHex.add(k); return hex }
    return HEX_TOKENS[k] ? `var(${HEX_TOKENS[k]})` : hex
  })
}

function scopeCss(css, scope) {
  const tree = postcss.parse(css)
  const renames = new Map()
  tree.walkAtRules(/keyframes$/, (at) => {
    const name = at.params.trim()
    if (!name.startsWith('vc-')) {
      renames.set(name, `vc-${name}`)
      at.params = `vc-${name}`
    }
  })
  tree.walkRules((rule) => {
    const parent = rule.parent
    if (parent && parent.type === 'atrule' && /keyframes$/.test(parent.name)) return
    rule.selectors = rule.selectors.map((s) => scopeSelector(s, scope))
  })
  tree.walkDecls((decl) => {
    if (/^(animation|animation-name)$/.test(decl.prop)) {
      for (const [from, to] of renames) {
        decl.value = decl.value.replace(new RegExp(`(^|[\\s,])${from}(?=$|[\\s,])`, 'g'), `$1${to}`)
      }
    }
    if (decl.value.includes('url(')) decl.value = rewriteUrls(decl.value)
    else decl.value = tokeniseHex(decl.value)
    // Fonts come from next/font (layout.tsx), never a hard-coded family name.
    if (decl.prop === '--sans') decl.value = 'var(--font-poppins), system-ui, sans-serif'
    if (decl.prop === '--mono') decl.value = "var(--font-jetbrains), 'JetBrains Mono', ui-monospace, monospace"
  })
  return tree.toString()
}

/** Keyframe names are global, so a page block's animations must match the renamed base ones. */
function renameKnownAnimations(css, names) {
  const tree = postcss.parse(css)
  tree.walkDecls(/^animation(-name)?$/, (decl) => {
    for (const n of names) {
      decl.value = decl.value.replace(new RegExp(`(^|[\\s,])${n}(?=$|[\\s,])`, 'g'), `$1vc-${n}`)
    }
  })
  return tree.toString()
}

const sys = readFileSync(join(src, 'sys.css'), 'utf8')
const baseKeyframes = [...sys.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1])
// Hand-written additions (booking skin, utilities) live next to this script.
const extras = readFileSync(new URL('./extras.css', import.meta.url), 'utf8')
const baseCss = `${scopeCss(sys, '.vc')}\n${extras}`
const teamCardCss = readFileSync(new URL('./team-card.css', import.meta.url), 'utf8')
// One self-contained file per page: base + extras + that page's block, in
// that order, so production CSS chunking can never put the base after the
// page rules (equal specificity, so order decides, exactly as in the mock-ups).
writeFileSync(join(outDir, 'default.css'), tokeniseColors(`${HEADER}@layer components {\n${baseCss}\n}\n`))
console.log(`base  ${sys.length} bytes in`)

const pages = [
  ...readdirSync(join(src, 'p')).filter((f) => f.endsWith('.html')).map((f) => [f.slice(0, -5), join(src, 'p', f)]),
  ['monday-implementation-consultants', join(src, 'c.html')],
]
let n = 0
for (const [slug, file] of pages) {
  const html = readFileSync(file, 'utf8')
  const blocks = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n')
  if (!blocks.trim()) continue
  // Page blocks may animate with base keyframes (mq-up etc.): rename those first.
  const css = scopeCss(renameKnownAnimations(blocks, baseKeyframes), `.vc-p-${slug}`)
  // Hand-written fixes for one page (scripts/vc/extras-<slug>.css) go after its block.
  const pageExtrasFile = new URL(`./extras-${slug}.css`, import.meta.url)
  const pageExtras = existsSync(pageExtrasFile) ? `\n${readFileSync(pageExtrasFile, 'utf8')}` : ''
  // The six region pages share one team card (the /fruition-team card): scripts/vc/team-card.css.
  const teamCard = slug.startsWith('monday-partner-') ? `\n${teamCardCss}` : ''
  writeFileSync(
    join(outDir, 'pages', `${slug}.css`),
    // Raw purples (shadows, glows) become token-based so Blue mode reaches them.
    tokeniseColors(`${HEADER}@layer components {\n${baseCss}\n${css}${pageExtras}${teamCard}\n}\n`),
  )
  n++
}
console.log(`${n} page stylesheets written`)
writeDerived()
if (unknownHex.size) console.warn(`untokenised colours: ${[...unknownHex].join(' ')}`)
