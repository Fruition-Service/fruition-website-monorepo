/**
 * Rewrites the html[data-palette="blue"] block in src/app/globals.css from the
 * :root tokens, using toBlue() from src/lib/palette.ts. Run after adding or
 * changing a purple token, or after changing the Blue mode formula:
 *
 *   npx tsx scripts/palette/sync-blue-tokens.ts
 *
 * palette.test.ts fails while the block is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { coloursIn, isPurple, toBlue } from "../../src/lib/palette"

const FILE = join(__dirname, "..", "..", "src", "app", "globals.css")
const OPEN = 'html[data-palette="blue"] {'

const css = readFileSync(FILE, "utf8")
const start = css.indexOf(OPEN)
if (start < 0) throw new Error(`${OPEN} not found in globals.css`)
const end = css.indexOf("}", start)
const root = css.slice(0, start)

const tokens = new Map<string, string>()
for (const m of root.matchAll(/^\s*(--[\w-]+):\s*(#[0-9a-fA-F]{6});/gm)) tokens.set(m[1], m[2])
const twin = (name: string) => {
  const v = tokens.get(name)
  if (!v) throw new Error(`token ${name} missing from :root`)
  return toBlue(v)
}

const lines = [...tokens]
  .filter(([, v]) => isPurple(coloursIn(v)[0]))
  .map(([n, v]) => `  ${n}: ${toBlue(v)};`)

const body = `
  /* Generated by scripts/palette/sync-blue-tokens.ts: every purple :root token
     as its blue twin (the brand purple becomes LinkedIn blue). */
${lines.join("\n")}

  /* Not purple, but follow the brand in Blue mode. The Implementation Calculator
     launcher fades blue to dark blue instead of to pink, and the CTA ramp uses
     the brand blue so buttons and headings share one blue. */
  --fruit-pink: ${twin("--purple-dark")};
  --cta-blue: ${twin("--purple-primary")};
  --cta-blue-light: ${twin("--purple-primary")};
  --cta-blue-dark: ${twin("--vc-accent-press")};
  --cta-blue-soft: ${twin("--purple-soft")};
  --cta-blue-pale: ${twin("--vc-accent-on-dark")};
  --cta-blue-deep: ${twin("--navy-900")};
`

writeFileSync(FILE, css.slice(0, start + OPEN.length) + body + css.slice(end))
console.log(`wrote ${lines.length} token twins + 7 brand overrides`)
